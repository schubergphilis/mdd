class TestLoadTone:
    def test_default_tone_exists(self) -> None:
        path = _default_tone_path()
        assert path.exists(), f"Default tone prompt not found: {path}"

    def test_default_tone_returns_digest(self) -> None:
        text, digest = _load_tone(None)
        assert isinstance(text, str)
        assert len(text) > 0
        assert isinstance(digest, bytes)
        assert len(digest) == 32  # SHA-256

    def test_custom_tone(self, tmp_path: Path) -> None:
        style_file = tmp_path / "my-style.md"
        style_file.write_text("Be very concise.", encoding="utf-8")
        text, digest = _load_tone(style_file)
        assert text == "Be very concise."
        expected_digest = hashlib.sha256(b"Be very concise.").digest()
        assert digest == expected_digest

    def test_different_tones_produce_different_digests(self, tmp_path: Path) -> None:
        a = tmp_path / "a.md"
        b = tmp_path / "b.md"
        a.write_text("Style A", encoding="utf-8")
        b.write_text("Style B", encoding="utf-8")
        _, da = _load_tone(a)
        _, db = _load_tone(b)
        assert da != db


class TestLoadConstraints:
    def test_constraints_file_exists(self) -> None:
        text, digest = _load_constraints()
        assert isinstance(text, str)
        assert len(text) > 0
        assert isinstance(digest, bytes)
        assert len(digest) == 32

    def test_constraints_mention_placeholder_preservation(self) -> None:
        text, _ = _load_constraints()
        # The load-bearing instruction must be present — this is the
        # whole point of splitting the prompt: --style cannot drop it.
        assert "placeholder" in text.lower()


class TestComposeSystemPrompt:
    def test_combines_tone_and_constraints(self) -> None:
        composed = _compose_system_prompt("TONE_BLOCK", "CONSTRAINTS_BLOCK")
        assert "TONE_BLOCK" in composed
        assert "CONSTRAINTS_BLOCK" in composed
        # Constraints come AFTER tone so they're the trailing instructions.
        assert composed.index("TONE_BLOCK") < composed.index("CONSTRAINTS_BLOCK")

    def test_custom_tone_preserves_bundled_constraints(self) -> None:
        constraints_text, _ = _load_constraints()
        composed = _compose_system_prompt("Be terse.", constraints_text)
        # The user-supplied tone cannot drop the placeholder rule.
        assert "placeholder" in composed.lower()


