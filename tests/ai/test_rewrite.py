class TestRewriteFile:
    def test_produces_sibling_by_default(self, tmp_path: Path) -> None:
        src = tmp_path / "page.md"
        src.write_text("# Hello\n\nSome text.\n", encoding="utf-8")

        mock_client = _make_mock_client("# Hello\n\nRewritten text.\n")

        result = rewrite_file(src, mock_client)  # pyright: ignore[reportArgumentType]

        assert result.status == "rewritten"
        assert result.output_path == tmp_path / "page.md.rewrite.md"
        assert result.output_path is not None
        assert result.output_path.exists()
        assert "Rewritten text." in result.output_path.read_text()

    def test_apply_overwrites_in_place(self, tmp_path: Path) -> None:
        src = tmp_path / "page.md"
        src.write_text("# Hello\n\nOriginal text.\n", encoding="utf-8")

        mock_client = _make_mock_client("# Hello\n\nApplied text.\n")

        result = rewrite_file(src, mock_client, apply=True)  # pyright: ignore[reportArgumentType]

        assert result.status == "rewritten"
        assert result.output_path == src
        assert "Applied text." in src.read_text()

    def test_frontmatter_preserved_byte_identical(self, tmp_path: Path) -> None:
        fm = "---\ntitle: Test\nconfluence:\n  page_id: '123'\n---\n"
        body = "\n# Body\n\nSome prose.\n"
        src = tmp_path / "page.md"
        src.write_text(fm + body, encoding="utf-8")

        # Model returns only the body (no frontmatter in model output).
        mock_client = _make_mock_client("# Body\n\nRewritten prose.\n")

        result = rewrite_file(src, mock_client, apply=True)  # pyright: ignore[reportArgumentType]

        assert result.status == "rewritten"
        content = src.read_text()
        assert content.startswith(fm)

    def test_boundary_whitespace_restored(self, tmp_path: Path) -> None:
        # Source has a blank line after the frontmatter and trailing blank lines.
        fm = "---\ntitle: Test\n---\n"
        body = "\n> Header\n\n# Title\n\n{{confluence:children}}\n\n  \n\n"
        src = tmp_path / "page.md"
        src.write_text(fm + body, encoding="utf-8")

        # Model trims the leading blank line and all trailing whitespace.
        mock_client = _make_mock_client("> Header\n\n# Title\n\n{{confluence:children}}")

        result = rewrite_file(src, mock_client, apply=True)  # pyright: ignore[reportArgumentType]

        assert result.status == "rewritten"
        # Boundary whitespace matches the source exactly — no churn.
        assert src.read_text(encoding="utf-8") == fm + body

    def test_boundary_whitespace_only_whitespace_body_preserved(self, tmp_path: Path) -> None:
        body = "\n\n  \n"
        src = tmp_path / "page.md"
        src.write_text(body, encoding="utf-8")

        mock_client = _make_mock_client("   \n")

        result = rewrite_file(src, mock_client, apply=True)  # pyright: ignore[reportArgumentType]

        assert result.status == "rewritten"
        assert src.read_text(encoding="utf-8") == body

    def test_missing_placeholder_returns_error(self, tmp_path: Path) -> None:
        src = tmp_path / "page.md"
        src.write_text("Some prose.\n\n```python\nx=1\n```\n\nMore prose.\n", encoding="utf-8")

        # Model drops the placeholder.
        mock_client = _make_mock_client("Some prose. More prose.")

        result = rewrite_file(src, mock_client)  # pyright: ignore[reportArgumentType]

        assert result.status == "error"
        assert "missing" in (result.error or "").lower()

    def test_cache_hit_returns_cached_status(self, tmp_path: Path) -> None:
        src = tmp_path / "page.md"
        src.write_text("# Hello\n\nSome text.\n", encoding="utf-8")

        mock_client = _make_mock_client("# Hello\n\nCached text.\n", cached=True)

        result = rewrite_file(src, mock_client)  # pyright: ignore[reportArgumentType]

        assert result.status == "cached"

    def test_file_not_found_returns_error(self, tmp_path: Path) -> None:
        src = tmp_path / "nonexistent.md"
        mock_client = MagicMock()

        result = rewrite_file(src, mock_client)  # pyright: ignore[reportArgumentType]

        assert result.status == "error"
        assert "not found" in (result.error or "").lower()

    def test_style_hash_used_in_cache_key(self, tmp_path: Path) -> None:
        """Different style files must produce different cache keys."""
        src = tmp_path / "page.md"
        src.write_text("# Hello\n\nText.\n", encoding="utf-8")

        style_a = tmp_path / "style_a.md"
        style_b = tmp_path / "style_b.md"
        style_a.write_text("Style A", encoding="utf-8")
        style_b.write_text("Style B", encoding="utf-8")

        call_extras: list[bytes] = []

        def capture_chat(**kwargs: Any) -> ChatResult:  # pyright: ignore[reportAny]
            call_extras.append(kwargs.get("cache_key_extra", b""))
            return _make_chat_result("# Hello\n\nResult.\n")

        mock_client = MagicMock()
        mock_client.chat.side_effect = capture_chat
        mock_client.summary.api_calls = 0
        mock_client.summary.prompt_tokens = 0
        mock_client.summary.completion_tokens = 0
        mock_client.summary.cost_usd = 0.0

        rewrite_file(src, mock_client, style_path=style_a)  # pyright: ignore[reportArgumentType]
        rewrite_file(src, mock_client, style_path=style_b)  # pyright: ignore[reportArgumentType]

        assert len(call_extras) == 2
        assert call_extras[0] != call_extras[1]

    def test_code_block_preserved_through_rewrite(self, tmp_path: Path) -> None:
        """Protected code blocks must be byte-identical after rewrite."""
        code_block = "```python\ndef my_func():\n    return 42\n```"
        src = tmp_path / "page.md"
        src.write_text(f"Intro prose.\n\n{code_block}\n\nOutro prose.\n", encoding="utf-8")

        # Model returns transformed prose with placeholder preserved
        def identity_model(**kwargs: Any) -> ChatResult:  # pyright: ignore[reportAny]
            user_text: str = kwargs["user"]
            # Replace non-placeholder text with uppercase, leave placeholder.
            import re

            parts = re.split(r"(__MDD_PROTECTED_\d+__)", user_text)
            out = "".join(p if p.startswith("__MDD_PROTECTED_") else p.upper() for p in parts)
            return _make_chat_result(out)

        mock_client = MagicMock()
        mock_client.chat.side_effect = identity_model
        mock_client.summary.api_calls = 1
        mock_client.summary.prompt_tokens = 10
        mock_client.summary.completion_tokens = 5
        mock_client.summary.cost_usd = 0.0

        result = rewrite_file(src, mock_client, apply=True)  # pyright: ignore[reportArgumentType]

        assert result.status == "rewritten"
        content = src.read_text()
        assert code_block in content

    def test_table_preserved_through_rewrite(self, tmp_path: Path) -> None:
        table = "| A | B |\n|---|---|\n| 1 | 2 |\n"
        src = tmp_path / "page.md"
        src.write_text(f"Intro.\n\n{table}\nOutro.\n", encoding="utf-8")

        def identity_model(**kwargs: Any) -> ChatResult:  # pyright: ignore[reportAny]
            user_text: str = kwargs["user"]
            import re

            parts = re.split(r"(__MDD_PROTECTED_\d+__)", user_text)
            out = "".join(p if p.startswith("__MDD_PROTECTED_") else p.upper() for p in parts)
            return _make_chat_result(out)

        mock_client = MagicMock()
        mock_client.chat.side_effect = identity_model
        mock_client.summary.api_calls = 1
        mock_client.summary.prompt_tokens = 10
        mock_client.summary.completion_tokens = 5
        mock_client.summary.cost_usd = 0.0

        result = rewrite_file(src, mock_client, apply=True)  # pyright: ignore[reportArgumentType]

        assert result.status == "rewritten"
        content = src.read_text()
        assert table in content


