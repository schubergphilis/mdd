class TestSplitFrontmatter:
    def test_no_frontmatter(self) -> None:
        body = "# Title\n\nContent"
        fm, b = _split_frontmatter(body)
        assert fm == ""
        assert b == body

    def test_with_frontmatter(self) -> None:
        text = "---\ntitle: Test\n---\n\n# Body"
        fm, b = _split_frontmatter(text)
        assert fm == "---\ntitle: Test\n---\n"
        assert b == "\n# Body"

    def test_frontmatter_not_sent_to_model(self) -> None:
        """The frontmatter block must NOT appear in the body sent to the model."""
        text = "---\ntitle: Secret\nauthor: Alice\n---\n\nBody here."
        _fm, b = _split_frontmatter(text)
        assert "title: Secret" not in b
        assert "Body here." in b


