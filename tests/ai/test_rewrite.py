class TestRewriteFiles:
    def test_processes_all_files(self, tmp_path: Path) -> None:
        a = tmp_path / "a.md"
        b = tmp_path / "b.md"
        a.write_text("File A content.\n", encoding="utf-8")
        b.write_text("File B content.\n", encoding="utf-8")

        mock_client = _make_mock_client("Rewritten content.\n")

        results = rewrite_files([a, b], mock_client)  # pyright: ignore[reportArgumentType]

        assert len(results) == 2
        assert all(r.status == "rewritten" for r in results)

    def test_error_in_one_does_not_stop_others(self, tmp_path: Path) -> None:
        a = tmp_path / "a.md"
        b = tmp_path / "missing.md"  # does not exist
        c = tmp_path / "c.md"
        a.write_text("Content A.\n", encoding="utf-8")
        c.write_text("Content C.\n", encoding="utf-8")

        mock_client = _make_mock_client("Rewritten.\n")

        results = rewrite_files([a, b, c], mock_client)  # pyright: ignore[reportArgumentType]

        assert len(results) == 3
        assert results[0].status == "rewritten"
        assert results[1].status == "error"
        assert results[2].status == "rewritten"

    def test_serial_execution_order(self, tmp_path: Path) -> None:
        """Files must be processed in the order given (serial, not parallel)."""
        order: list[str] = []

        def ordered_chat(**kwargs: Any) -> ChatResult:  # pyright: ignore[reportAny]
            user: str = kwargs["user"]
            order.append(user[:6])  # first chars identify the file
            return _make_chat_result("Done.\n")

        mock_client = MagicMock()
        mock_client.chat.side_effect = ordered_chat
        mock_client.summary.api_calls = 0
        mock_client.summary.prompt_tokens = 0
        mock_client.summary.completion_tokens = 0
        mock_client.summary.cost_usd = 0.0

        files: list[Path] = []
        for i in range(3):
            p = tmp_path / f"file{i}.md"
            p.write_text(f"file{i} content here.\n", encoding="utf-8")
            files.append(p)

        rewrite_files(files, mock_client)  # pyright: ignore[reportArgumentType]

        # Verify processing happened in order (each call contained file identifier)
        assert len(order) == 3
        assert order[0].startswith("file0")
        assert order[1].startswith("file1")
        assert order[2].startswith("file2")


