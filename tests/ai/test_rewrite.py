class TestProtectedRegionPipeline:
    def test_no_protected_regions(self) -> None:
        text = "Hello world.\n\nSome more text."
        transformed, regions = extract_protected(text)
        assert transformed == text
        assert regions == []

    def test_frontmatter_extracted(self) -> None:
        text = "---\ntitle: Test\n---\n\nBody text here."
        transformed, regions = extract_protected(text)
        assert "---\ntitle: Test\n---\n" in regions[0].original
        assert "__MDD_PROTECTED_0__" in transformed
        assert "Body text here." in transformed

    def test_code_block_extracted(self) -> None:
        text = "Before\n\n```python\nx = 1\n```\n\nAfter"
        transformed, _regions = extract_protected(text)
        assert "```python" not in transformed
        assert "__MDD_PROTECTED_0__" in transformed
        assert "Before" in transformed
        assert "After" in transformed

    def test_fenced_confluence_block_extracted(self) -> None:
        text = "Prose\n\n```{=confluence}\n<ac:macro/>\n```\n\nMore prose"
        transformed, regions = extract_protected(text)
        assert "{=confluence}" not in transformed
        assert len(regions) == 1
        assert "{=confluence}" in regions[0].original

    def test_fenced_html_block_extracted(self) -> None:
        text = "Prose\n\n```{=html}\n<div>test</div>\n```\n\nMore"
        transformed, regions = extract_protected(text)
        assert "{=html}" not in transformed
        assert len(regions) == 1

    def test_table_extracted(self) -> None:
        table = "| A | B |\n|---|---|\n| 1 | 2 |\n"
        text = f"Before\n\n{table}\nAfter"
        transformed, regions = extract_protected(text)
        assert "| A |" not in transformed
        assert len(regions) == 1
        assert "| A |" in regions[0].original

    def test_confluence_export_header_extracted(self) -> None:
        header = "> **Confluence export** — Auto-generated.\n> Source: https://example.com\n"
        text = f"{header}\n# Title\n\nBody"
        transformed, regions = extract_protected(text)
        assert "> **Confluence export**" not in transformed
        assert len(regions) == 1
        assert "> **Confluence export**" in regions[0].original

    def test_mdd_footer_extracted(self) -> None:
        footer = "> *Generated by mdd — https://github.com/schubergphilis/mdd*\n"
        text = f"Body text\n\n{footer}"
        transformed, regions = extract_protected(text)
        assert "> *Generated by mdd" not in transformed
        assert len(regions) == 1
        assert "> *Generated by mdd" in regions[0].original

    def test_multiple_protected_regions(self) -> None:
        text = "```python\nx=1\n```\n\nProse middle\n\n| A | B |\n|---|---|\n| 1 | 2 |\n\nEnd"
        transformed, regions = extract_protected(text)
        assert len(regions) == 2
        assert "__MDD_PROTECTED_0__" in transformed
        assert "__MDD_PROTECTED_1__" in transformed
        assert "Prose middle" in transformed
        assert "End" in transformed

    def test_round_trip_preserves_content(self) -> None:
        """Extract → uppercase prose (model stub) → stitch → identical protected content."""
        text = (
            "---\ntitle: Doc\n---\n\n"
            "This is prose.\n\n"
            "```python\nx = 42\n```\n\n"
            "More prose.\n\n"
            "| H1 | H2 |\n|----|----|\n| a  | b  |\n"
        )
        transformed, regions = extract_protected(text)

        # Simulate a model that uppercases all text (but leaves placeholders alone).
        def uppercase_non_placeholder(t: str) -> str:
            import re

            parts = re.split(r"(__MDD_PROTECTED_\d+__)", t)
            return "".join(p if p.startswith("__MDD_PROTECTED_") else p.upper() for p in parts)

        model_output = uppercase_non_placeholder(transformed)
        result = stitch_protected(model_output, regions)

        # Protected regions must be byte-identical.
        assert "---\ntitle: Doc\n---\n" in result
        assert "```python\nx = 42\n```" in result
        assert "| H1 | H2 |" in result

    def test_stitch_raises_on_missing_placeholder(self) -> None:
        text = "Prose\n\n```code\ncontent\n```\n\nMore"
        _, regions = extract_protected(text)
        # Simulate model that dropped the placeholder
        bad_output = "PROSE\n\nMORE"
        with pytest.raises(ValueError, match="missing from the model"):
            stitch_protected(bad_output, regions)

    def test_full_protected_fixture(self) -> None:
        """All protected types in the fixture file round-trip correctly."""
        content = (FIXTURES_DIR / "protected.md").read_text(encoding="utf-8")
        transformed, regions = extract_protected(content)

        # Simulate a model that returns the transformed text as-is (identity).
        result = stitch_protected(transformed, regions)
        assert result == content

    def test_tilde_fenced_block_extracted(self) -> None:
        text = "Before\n\n~~~\nsome content\n~~~\n\nAfter"
        transformed, regions = extract_protected(text)
        assert "~~~" not in transformed
        assert len(regions) == 1


