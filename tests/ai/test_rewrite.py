def _make_chat_result(text: str, cached: bool = False) -> ChatResult:
    return ChatResult(
        text=text,
        cached=cached,
        prompt_tokens=10,
        completion_tokens=5,
        cost_usd=None,
    )


def _make_mock_client(return_text: str, cached: bool = False) -> MagicMock:
    """Return a mock Client whose chat() returns the given text."""
    mock = MagicMock()
    mock.chat.return_value = _make_chat_result(return_text, cached=cached)
    mock.summary.api_calls = 1
    mock.summary.prompt_tokens = 10
    mock.summary.completion_tokens = 5
    mock.summary.cost_usd = 0.0
    return mock


