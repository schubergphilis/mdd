"""AI-powered markdown rewrite with protected-region pipeline.

Usage::

    from mdd.ai.rewrite import rewrite_file, RewriteResult

    result = rewrite_file(
        path=Path("docs/my-page.md"),
        client=client,
        style_path=None,   # use bundled default
        apply=False,       # write <file>.rewrite.md sibling
    )
    print(result.status)  # "rewritten" | "cached" | "error"
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

import yaml  # pyright: ignore[reportMissingModuleSource]

from mdd.utils.logging import get_logger

if TYPE_CHECKING:
    from mdd.ai.client import Client

log = get_logger(__name__)

# ---------------------------------------------------------------------------
# Protected-region pipeline
# ---------------------------------------------------------------------------

# Placeholder format: unique enough to survive model paraphrasing of prose.
_PLACEHOLDER_PREFIX = "__MDD_PROTECTED_"
_PLACEHOLDER_SUFFIX = "__"

# Patterns that mark protected regions, in priority order.
# Each entry is (name, compiled_regex).  The regex must capture the full
# protected span (possibly multi-line).
#
# Order matters for overlapping patterns: frontmatter first, then fenced
# blocks (longest-first among opening fences), then tables.
_PROTECTED_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    # YAML frontmatter at the very start of the file
    (
        "frontmatter",
        re.compile(r"\A---\n.*?\n---\n?", re.DOTALL),
    ),
    # Fenced code / raw blocks with any info string (``` or ~~~, 3+ chars)
    # including {=confluence}, {=html}, etc.
    (
        "fenced",
        re.compile(r"(?m)^(`{3,}|~{3,})[^\n]*\n.*?\n\1[ \t]*$", re.DOTALL),
    ),
    # Confluence export header: the blockquote that starts a Confluence export
    # ("> **Confluence export …" up to the next blank line or heading)
    (
        "export_header",
        re.compile(
            r"(?m)^> \*\*Confluence export[^\n]*\n(?:>[^\n]*\n)*",
            re.DOTALL,
        ),
    ),
    # MDD footer: the blockquote that ends with MDD-generated content marker
    # ("> *Generated by mdd …" at the end of the file)
    (
        "mdd_footer",
        re.compile(
            r"(?m)^> \*Generated by mdd[^\n]*\n?$",
            re.DOTALL,
        ),
    ),
    # Markdown tables: lines where every non-empty line begins with |
    # A table block is the contiguous run of pipe-lines.
    (
        "table",
        re.compile(r"(?m)(?:^\|[^\n]*\n)+"),
    ),
]


@dataclass
class _Region:
    placeholder: str
    original: str


def extract_protected(text: str) -> tuple[str, list[_Region]]:
    """Replace protected regions in *text* with sequential placeholder tokens.

    Returns the transformed text and the list of replaced regions in order.
    Protected regions are guaranteed to round-trip byte-identically.
    """
    regions: list[_Region] = []
    idx = 0
    result_parts: list[str] = []
    pos = 0  # current scan position

    while pos < len(text):
        earliest_match: re.Match[str] | None = None
        earliest_start = len(text)

        for _name, pattern in _PROTECTED_PATTERNS:
            m = pattern.search(text, pos)
            if m and m.start() < earliest_start:
                earliest_match = m
                earliest_start = m.start()

        if earliest_match is None:
            # No more protected regions — append the rest.
            result_parts.append(text[pos:])
            break

        # Append text before the match.
        result_parts.append(text[pos : earliest_match.start()])

        placeholder = f"{_PLACEHOLDER_PREFIX}{idx}{_PLACEHOLDER_SUFFIX}"
        regions.append(_Region(placeholder=placeholder, original=earliest_match.group()))
        result_parts.append(placeholder)
        idx += 1
        pos = earliest_match.end()

    return "".join(result_parts), regions


def stitch_protected(text: str, regions: list[_Region]) -> str:
    """Replace placeholder tokens back with their original protected content.

    Raises ValueError if any placeholder is missing from *text*.
    """
    for region in regions:
        if region.placeholder not in text:
            raise ValueError(
                f"Protected-region placeholder {region.placeholder!r} is missing from "
                "the model's output. The model likely removed or rewrote a protected "
                "block. Refusing to produce output — the rewrite is unsafe."
            )
        text = text.replace(region.placeholder, region.original, 1)
    return text


# ---------------------------------------------------------------------------
# Prompt loading
# ---------------------------------------------------------------------------


def _default_tone_path() -> Path:
    """Return the path to the bundled default tone-of-voice prompt.

    Users can override this via ``--style <path>`` to swap in their own
    voice. The constraints block (placeholder preservation, pass-through
    rules) is always composed on top — see :func:`_load_constraints` and
    :func:`_compose_system_prompt`.
    """
    return Path(__file__).parent / "prompts" / "tone-of-voice.md"


def _constraints_path() -> Path:
    """Return the path to the bundled rewrite-constraints prompt.

    This block carries the load-bearing rules (preserve placeholder tokens,
    do not alter substance, return only the rewritten body) and is NEVER
    overridable — ``--style`` only swaps the tone block.
    """
    return Path(__file__).parent / "prompts" / "rewrite-constraints.md"


def _load_tone(path: Path | None) -> tuple[str, bytes]:
    """Load the tone-of-voice prompt and return (text, sha256_digest).

    *path* is None → use the bundled default.
    """
    resolved = path if path is not None else _default_tone_path()
    text = resolved.read_text(encoding="utf-8")
    digest = hashlib.sha256(text.encode()).digest()
    return text, digest


def _load_constraints() -> tuple[str, bytes]:
    """Load the immutable constraints prompt and return (text, sha256_digest)."""
    text = _constraints_path().read_text(encoding="utf-8")
    digest = hashlib.sha256(text.encode()).digest()
    return text, digest


def _compose_system_prompt(tone_text: str, constraints_text: str) -> str:
    """Compose the rewrite system prompt as ``tone\\n\\n---\\n\\n{constraints}``.

    The constraints block always lands after the tone block so a model that
    pays more attention to the trailing instructions still respects the
    placeholder-preservation rules.
    """
    return f"{tone_text.rstrip()}\n\n---\n\n{constraints_text.lstrip()}"


# ---------------------------------------------------------------------------
# Body extraction (strip frontmatter for model input)
# ---------------------------------------------------------------------------


def _split_frontmatter(text: str) -> tuple[str, str]:
    """Split *text* into (frontmatter_block, body).

    *frontmatter_block* includes the ``---\\n...\\n---\\n`` delimiters, or is
    empty if no frontmatter is present.  *body* is the remainder.
    """
    if not (text.startswith(("---\n", "---\r\n"))):
        return "", text

    rest = text[4:]
    end_idx = rest.find("\n---\n")
    if end_idx == -1:
        if rest.endswith("\n---"):
            end_idx = len(rest) - 4
            return text[: 4 + end_idx + 4], rest[end_idx + 4 :]
        return "", text

    fm_end = 4 + end_idx + 5  # "---\n" + yaml + "\n---\n"
    return text[:fm_end], text[fm_end:]


def _restore_boundary_whitespace(original_body: str, new_body: str) -> str:
    """Re-attach *original_body*'s leading/trailing whitespace to *new_body*.

    The model routinely trims the blank line that follows the frontmatter
    delimiter or drops the trailing newline, producing whitespace-only diffs
    against the source.  We keep only the model's interior content and restore
    the source body's exact leading and trailing whitespace, so boundary
    whitespace never churns.
    """
    core = new_body.strip()
    if not core:
        # Model returned only whitespace; keep the source body verbatim.
        return original_body
    leading = original_body[: len(original_body) - len(original_body.lstrip())]
    trailing = original_body[len(original_body.rstrip()) :]
    return leading + core + trailing


