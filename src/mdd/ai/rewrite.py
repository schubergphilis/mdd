@dataclass
class RewriteResult:
    """Result of rewriting one file."""

    path: Path
    status: str  # "rewritten" | "cached" | "error"
    output_path: Path | None = None
    error: str | None = None
    prompt_tokens: int = 0
    completion_tokens: int = 0
    cost_usd: float | None = None


def _check_managed_for_apply(path: Path, full_text: str) -> bool:  # noqa: ARG001
    """Return True if the file's frontmatter indicates a managed-elsewhere page.

    Checks ``confluence.managed_by`` in the frontmatter (stamped by the
    pull-side logic).  Does not make any HTTP calls.
    """
    try:
        if not (full_text.startswith(("---\n", "---\r\n"))):
            return False
        rest = full_text[4:]
        end_idx = rest.find("\n---\n")
        if end_idx == -1:
            return False
        yaml_block = rest[:end_idx]
        fm_raw: Any = yaml.safe_load(yaml_block)  # pyright: ignore[reportAny]
        if not isinstance(fm_raw, dict):
            return False
        fm: dict[str, Any] = fm_raw  # pyright: ignore[reportUnknownVariableType]
        conf_raw: Any = fm.get("confluence")  # pyright: ignore[reportAny]
        if not isinstance(conf_raw, dict):
            return False
        conf: dict[str, Any] = conf_raw  # pyright: ignore[reportUnknownVariableType]
        managed_by: Any = conf.get("managed_by")  # pyright: ignore[reportAny]
        return bool(managed_by)
    except Exception:
        return False


def rewrite_file(  # noqa: C901, PLR0911, PLR0912, PLR0915
    path: Path,
    client: Client,
    *,
    style_path: Path | None = None,
    apply: bool = False,
    model: str | None = None,
) -> RewriteResult:
    """Rewrite a single markdown file via the AI client.

    Parameters
    ----------
    path:
        The source markdown file.
    client:
        An initialised ``mdd.ai.Client`` instance.
    style_path:
        Override the default tone-of-voice prompt file.  ``None`` → bundled
        default.
    apply:
        If ``True``, overwrite *path* in place (atomic tmp→rename).
        If ``False``, write a ``<path>.rewrite.md`` sibling.
    model:
        Override the model selection.  ``None`` → use ``task="default"``
        from the client config.

    Returns
    -------
    RewriteResult
    """
    if not path.exists():
        return RewriteResult(
            path=path,
            status="error",
            error=f"File not found: {path}",
        )

    try:
        full_text = path.read_text(encoding="utf-8")
    except OSError as exc:
        return RewriteResult(path=path, status="error", error=str(exc))

    try:
        tone_text, tone_digest = _load_tone(style_path)
    except OSError as exc:
        return RewriteResult(path=path, status="error", error=f"Cannot read style file: {exc}")

    try:
        constraints_text, constraints_digest = _load_constraints()
    except OSError as exc:
        return RewriteResult(
            path=path,
            status="error",
            error=f"Cannot read constraints prompt: {exc}",
        )

    system_prompt = _compose_system_prompt(tone_text, constraints_text)

    # Split off frontmatter so it is not sent to the model.
    frontmatter_block, body = _split_frontmatter(full_text)

    # Compute the body hash for the cache key.
    body_hash = hashlib.sha256(body.encode()).digest()

    # Extract protected regions from the body.
    transformed_body, regions = extract_protected(body)

    # Cache key extra: body + tone + constraints. Constraints digest is
    # included so a bundled-prompt upgrade invalidates stale rewrites.
    cache_key_extra = body_hash + tone_digest + constraints_digest

    try:
        result = client.chat(
            system=system_prompt,
            user=transformed_body,
            task="default",
            model=model,
            cache_key_extra=cache_key_extra,
        )
    except Exception as exc:
        return RewriteResult(path=path, status="error", error=str(exc))

    # Stitch protected regions back.
    try:
        rewritten_body = stitch_protected(result.text, regions)
    except ValueError as exc:
        return RewriteResult(path=path, status="error", error=str(exc))

    # Restore the source body's boundary whitespace to avoid whitespace-only churn.
    rewritten_body = _restore_boundary_whitespace(body, rewritten_body)

    rewritten_full = frontmatter_block + rewritten_body

    # When --apply is set, check for managed-elsewhere before overwriting.
    if apply:
        try:
            _apply_blocked = _check_managed_for_apply(path, full_text)
        except Exception:
            _apply_blocked = False
        if _apply_blocked:
            # Refuse apply but still emit the candidate sibling.
            out_path = path.parent / (path.name + ".rewrite.md")
            tmp_path = out_path.with_suffix(out_path.suffix + ".tmp")
            try:
                tmp_path.write_text(rewritten_full, encoding="utf-8")
                tmp_path.replace(out_path)
            except OSError as exc:
                tmp_path.unlink(missing_ok=True)
                return RewriteResult(path=path, status="error", error=f"Write failed: {exc}")
            return RewriteResult(
                path=path,
                status="error",
                error=(
                    f"Managed-elsewhere page: --apply refused. Candidate written to {out_path}."
                ),
                output_path=out_path,
                prompt_tokens=result.prompt_tokens,
                completion_tokens=result.completion_tokens,
                cost_usd=result.cost_usd,
            )

    # Determine output path and write atomically.
    if apply:
        out_path = path
        tmp_path = path.with_suffix(path.suffix + ".tmp")
    else:
        out_path = path.parent / (path.name + ".rewrite.md")
        tmp_path = out_path.with_suffix(out_path.suffix + ".tmp")

    try:
        tmp_path.write_text(rewritten_full, encoding="utf-8")
        tmp_path.replace(out_path)
    except OSError as exc:
        tmp_path.unlink(missing_ok=True)
        return RewriteResult(path=path, status="error", error=f"Write failed: {exc}")

    return RewriteResult(
        path=path,
        status="cached" if result.cached else "rewritten",
        output_path=out_path,
        prompt_tokens=result.prompt_tokens,
        completion_tokens=result.completion_tokens,
        cost_usd=result.cost_usd,
    )


def rewrite_files(
    paths: list[Path],
    client: Client,
    *,
    style_path: Path | None = None,
    apply: bool = False,
    model: str | None = None,
) -> list[RewriteResult]:
    """Rewrite multiple files serially; there is deliberately no parallelism.

    Returns the list of results in the same order as *paths*.
    """
    results: list[RewriteResult] = []
    for p in paths:
        result = rewrite_file(p, client, style_path=style_path, apply=apply, model=model)
        results.append(result)
        _print_file_result(result)
    return results


def _print_file_result(result: RewriteResult) -> None:
    if result.status == "error":
        log.error("  error:    %s  — %s", result.path, result.error)
    elif result.status == "cached":
        log.info("  cached:   %s", result.path)
    else:
        log.info("  rewritten:%s  →  %s", result.path, result.output_path)


def print_run_summary(results: list[RewriteResult], client: Client) -> None:
    """Log a concise end-of-run summary."""
    cached = sum(1 for r in results if r.status == "cached")
    rewritten = sum(1 for r in results if r.status == "rewritten")
    errors = sum(1 for r in results if r.status == "error")
    summary = client.summary
    log.info(
        "Rewrite summary: %d rewritten, %d cached, %d error(s).",
        rewritten,
        cached,
        errors,
    )
    if summary.api_calls > 0:
        tokens = summary.prompt_tokens + summary.completion_tokens
        log.info(
            "  Tokens used: %s (prompt=%s, completion=%s)",
            f"{tokens:,}",
            f"{summary.prompt_tokens:,}",
            f"{summary.completion_tokens:,}",
        )
        if summary.cost_usd > 0:
            log.info("  Estimated cost: $%.4f", summary.cost_usd)
