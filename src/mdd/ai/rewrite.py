# Placeholder format: unique enough to survive model paraphrasing of prose.
_PLACEHOLDER_PREFIX = "__MDD_PROTECTED_"
_PLACEHOLDER_SUFFIX = "__"


class _Span(Protocol):
    """The subset of ``re.Match`` that ``extract_protected`` reads."""

    def start(self) -> int: ...

    def end(self) -> int: ...

    def group(self) -> str: ...


class _SpanMatch:
    def __init__(self, text: str, start: int, end: int) -> None:
        self._text = text
        self._start = start
        self._end = end

    def start(self) -> int:
        return self._start

    def end(self) -> int:
        return self._end

    def group(self) -> str:
        return self._text[self._start : self._end]


class _FencedBlockFinder:
    """``re.Pattern``-like ``search`` over fenced code blocks.

    The spans for the most recently seen text are cached so repeated
    ``search`` calls while walking one document stay linear overall.
    """

    def __init__(self) -> None:
        self._text: str | None = None
        self._spans: list[tuple[int, int]] = []

    def search(self, text: str, pos: int = 0) -> _Span | None:
        if text is not self._text:
            self._text = text
            self._spans = find_fenced_code_blocks(text)
        for start, end in self._spans:
            if start >= pos:
                return _SpanMatch(text, start, end)
        return None


# Patterns that mark protected regions, in priority order.
# Each entry is (name, finder); a finder is a compiled regex or an object
# with the same ``search`` shape, and must cover the full protected span
# (possibly multi-line).
#
# Order matters for overlapping patterns: frontmatter first, then fenced
# blocks (longest-first among opening fences), then tables.
_PROTECTED_PATTERNS: list[tuple[str, re.Pattern[str] | _FencedBlockFinder]] = [
    # YAML frontmatter at the very start of the file
    (
        "frontmatter",
        re.compile(r"\A---\n.*?\n---\n?", re.DOTALL),
    ),
    # Fenced code / raw blocks (``` or ~~~, 3+ chars) with any info string,
    # including {=confluence}, {=html}, etc. Located by a line scanner rather
    # than a backreference regex so large documents stay linear.
    ("fenced", _FencedBlockFinder()),
    # Confluence export header: the blockquote that starts a Confluence export
    # ("> **Confluence export …" up to the next blank line or heading)
    (
        "export_header",
        re.compile(
            r"(?m)^> \*\*Confluence export[^\n]*\n(?:>[^\n]*\n)*",
            re.DOTALL,
        ),
    ),
    # MDD footer: the blockquote that ends with MDD-generated content marker
    # ("> *Generated by mdd …" at the end of the file)
    (
        "mdd_footer",
        re.compile(
            r"(?m)^> \*Generated by mdd[^\n]*\n?$",
            re.DOTALL,
        ),
    ),
    # Markdown tables: lines where every non-empty line begins with |
    # A table block is the contiguous run of pipe-lines.
    (
        "table",
        re.compile(r"(?m)(?:^\|[^\n]*\n)+"),
    ),
]


@dataclass
class _Region:
    placeholder: str
    original: str
    kind: str = "unknown"


def extract_protected(text: str) -> tuple[str, list[_Region]]:
    """Replace protected regions in *text* with sequential placeholder tokens.

    Returns the transformed text and the list of replaced regions in order.
    Protected regions are guaranteed to round-trip byte-identically.
    """
    regions: list[_Region] = []
    idx = 0
    result_parts: list[str] = []
    pos = 0  # current scan position

    while pos < len(text):
        earliest_match: _Span | None = None
        earliest_start = len(text)
        earliest_kind = "unknown"

        for name, pattern in _PROTECTED_PATTERNS:
            m = pattern.search(text, pos)
            if m and m.start() < earliest_start:
                earliest_match = m
                earliest_start = m.start()
                earliest_kind = name

        if earliest_match is None:
            # No more protected regions — append the rest.
            result_parts.append(text[pos:])
            break

        # Append text before the match.
        result_parts.append(text[pos : earliest_match.start()])

        placeholder = f"{_PLACEHOLDER_PREFIX}{idx}{_PLACEHOLDER_SUFFIX}"
        regions.append(
            _Region(
                placeholder=placeholder,
                original=earliest_match.group(),
                kind=earliest_kind,
            )
        )
        result_parts.append(placeholder)
        idx += 1
        pos = earliest_match.end()

    return "".join(result_parts), regions


def stitch_protected(text: str, regions: list[_Region]) -> str:
    """Replace placeholder tokens back with their original protected content.

    Raises ValueError if any placeholder is missing from *text*.
    """
    for region in regions:
        if region.placeholder not in text:
            raise ValueError(
                f"Protected-region placeholder {region.placeholder!r} "
                f"(kind={region.kind}) is missing from "
                "the model's output. The model likely removed or rewrote a protected "
                "block. Refusing to produce output — the rewrite is unsafe."
            )
        text = text.replace(region.placeholder, region.original, 1)
    return text


# Matches both intact placeholders and mangled near-misses (case-folded,
# spaces or backticks inserted, index dropped), so diagnostics can say
# *how* the model damaged the token rather than only that it is gone.
_PLACEHOLDER_ISH = re.compile(
    r"[_`* ]{0,4}MDD[_`* -]{0,4}PROTECTED[_`* -]*\d*[_`* ]{0,4}",
    re.IGNORECASE,
)


def diagnose_placeholders(text: str, regions: list[_Region]) -> str:
    """Return a human-readable report on placeholder survival in *text*.

    Lists every protected region, whether its placeholder is present in the
    model's output, and any placeholder-like tokens the model emitted that
    do not match an expected placeholder exactly.
    """
    lines: list[str] = []
    lines.append(f"protected regions: {len(regions)}")
    for region in regions:
        present = region.placeholder in text
        preview = region.original.strip().splitlines()[0][:70] if region.original.strip() else ""
        lines.append(
            f"  {region.placeholder} kind={region.kind} "
            f"chars={len(region.original)} present={present} first_line={preview!r}"
        )

    expected = {r.placeholder for r in regions}
    found = {m.group().strip() for m in _PLACEHOLDER_ISH.finditer(text)}
    unexpected = sorted(tok for tok in found if tok not in expected)
    if unexpected:
        lines.append(f"placeholder-like tokens in output not matching any region: {unexpected}")
    return "\n".join(lines)


